export function ft(lang, key, vars) {
  const L = FREI_TEXTS[lang === "en" ? "en" : "de"], s = Object.prototype.hasOwnProperty.call(L, key) ? L[key] : "[" + key + "]";
  return vars ? s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] !== undefined ? String(vars[k]) : m)) : s;
}
export const has = (key) => Object.prototype.hasOwnProperty.call(FREI_TEXTS.de, key);
