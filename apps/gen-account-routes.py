#!/usr/bin/env python3
"""Generates the account bridge's EXACT allowlist for both shells from one source:
android/app/src/test/resources/bridge-account-v1.json (entries with "ok": true).
Writes ios/App/Duell/AccountRoutes.generated.swift, ios/Tests/AccountRouteCases.generated.swift and
android/app/src/main/java/org/bunsenbrenner/cads/duell/AccountRoutes.kt. `--check` fails when a file is stale
(apps/mdi/test/native.test.js checks the same, so a hand edit cannot drift).
Usage: python3 -I apps/gen-account-routes.py [--check]"""
import json, pathlib, sys

HERE = pathlib.Path(__file__).resolve().parent
SRC = HERE / "android/app/src/test/resources/bridge-account-v1.json"
HEAD = "// GENERATED by apps/gen-account-routes.py from android/app/src/test/resources/bridge-account-v1.json. Do not edit.\n"

def q(s):
    assert '"' not in s and "\\" not in s and "$" not in s, s
    return '"' + s + '"'

def outputs():
    cases = json.loads(SRC.read_text())["route"]
    allowed = sorted(c["method"] + " " + c["path"] for c in cases if c["ok"])
    sw = HEAD + "/// Exact list of the calls the page may ask for (method + path). Nothing else, no prefixes.\nenum AccountRoutes {\n    static let allowed: Set<String> = [\n" + "".join("        %s,\n" % q(a) for a in allowed) + "    ]\n}\n"
    kt = HEAD + "package org.bunsenbrenner.cads.duell\n\n/** Exact list of the calls the page may ask for (method + path). Nothing else, no prefixes. */\nobject AccountRoutes {\n    val ALLOWED: Set<String> = setOf(\n" + "".join("        %s,\n" % q(a) for a in allowed) + "    )\n}\n"
    tc = HEAD + "/// Every case of the shared fixture (allowed and refused).\nenum AccountRouteCases {\n    static let all: [(String, String, Bool)] = [\n" + "".join("        (%s, %s, %s),\n" % (q(c["method"]), q(c["path"]), "true" if c["ok"] else "false") for c in cases) + "    ]\n}\n"
    return {
        HERE / "ios/App/Duell/AccountRoutes.generated.swift": sw,
        HERE / "ios/Tests/AccountRouteCases.generated.swift": tc,
        HERE / "android/app/src/main/java/org/bunsenbrenner/cads/duell/AccountRoutes.kt": kt,
    }

if __name__ == "__main__":
    stale = []
    for path, text in outputs().items():
        if "--check" in sys.argv:
            if not path.exists() or path.read_text() != text: stale.append(str(path))
        else:
            path.write_text(text)
    if stale:
        sys.exit("stale, run python3 -I apps/gen-account-routes.py: " + ", ".join(stale))
